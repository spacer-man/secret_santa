export type Key = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];

@Injectable({ providedIn: 'root' })
export class I18n {
  private readonly tg = inject(Telegram);
  readonly lang = signal<'ru' | 'en'>(/^(ru|uk|be|kk)/.test(this.tg.language) ? 'ru' : 'en');

  get dict(): Dict {
    return this.lang() === 'ru' ? ru : en;
  }

  t(key: Key): string {
    return this.dict[key];
  }
}
